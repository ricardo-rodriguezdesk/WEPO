export const FUNCTIONS: FunctionInfo[] = NAMES.map(([en, es]) => {
  const doc = DOCS[en];
  return doc ? { en, es, description: doc[0], args: doc[1] } : { en, es };
});

/** Busca una función por su nombre en cualquiera de los dos idiomas. */
export function findFunction(name: string): FunctionInfo | undefined {
  const upper = name.toUpperCase();
  return FUNCTIONS.find((f) => f.en === upper || f.es === upper);
}

/** Funciones cuyo nombre (en el idioma elegido) empieza con `prefix`. Las documentadas, primero. */
export function suggestFunctions(prefix: string, language: "es" | "en", limit = 8): FunctionInfo[] {
  const upper = prefix.toUpperCase();
  if (!upper) return [];
  const matches = FUNCTIONS.filter((f) => f[language].startsWith(upper));
  matches.sort((a, b) => Number(Boolean(b.description)) - Number(Boolean(a.description)) || a[language].localeCompare(b[language]));
  return matches.slice(0, limit);
}
